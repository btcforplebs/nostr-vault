"""Builds HavenApp/HavenApp/Resources/emoji.tsv.
Inputs: Unicode emoji-test.txt 15.0 (https://unicode.org/Public/emoji/15.0/emoji-test.txt)
and CLDR 43 English annotations (common/annotations/en.xml + common/annotationsDerived/en.xml).
Usage: python3 -I scripts/gen-emoji-tsv.py emoji-test.txt en.xml en-derived.xml out.tsv"""
import sys, re, html
src, ann1, ann2, out = sys.argv[1:5]
kw = {}
for f in (ann1, ann2):
    for m in re.finditer(r'<annotation cp="([^"]+)">([^<]+)</annotation>', open(f, encoding="utf-8").read()):
        kw[html.unescape(m.group(1)).replace("️", "")] = [k.strip() for k in html.unescape(m.group(2)).split("|")]
skin = set(range(0x1F3FB, 0x1F400))
group = None
lines = ["# Unicode emoji 15.0 + CLDR 43 keywords. Generated by scripts/gen-emoji-tsv.py, do not edit.",
         "# '@' starts a group; other lines: emoji<TAB>name<TAB>extra keywords."]
for l in open(src, encoding="utf-8"):
    l = l.rstrip("\n")
    m = re.match(r"# group: (.*)", l)
    if m:
        group = m.group(1)
        if group != "Component": lines.append("@" + group)
        continue
    if not l or l.startswith("#") or group == "Component": continue
    cps, rest = l.split(";", 1)
    if "fully-qualified" not in rest.split("#")[0]: continue
    if any(int(c, 16) in skin for c in cps.split()): continue
    e, name = re.match(r".*# (\S+) E\d+\.\d+ (.*)", rest).groups()
    words = set(re.split(r"[\s:,]+", name.lower()))
    extra = []
    for k in kw.get(e.replace("️", ""), []):
        k = k.lower()
        if k != name.lower() and not set(k.split()) <= words and k not in extra: extra.append(k)
    lines.append(e + "\t" + name + "\t" + ", ".join(extra))
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
